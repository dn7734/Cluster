"""
НАУКОВО-МЕТОДИЧНИЙ ОПИС МОДУЛЯ (doc_generator.py):
Модуль автоматизованого формування проєктної та договірної документації у форматі Microsoft Word (DOCX).
Формує «Ескізний Проєкт (Драфт) та Рамкову Кластерну Угоду» за методологією ТОВ «Інститут інноваційної
біоекономіки» (ІІБ) на основі презентації «1_Драфт.pptx» (кейс: сорт гірчиці білої «Біла Принцеса»).
Відображає:
- Надбудову ІІБ НАД виробничим ланцюгом;
- 4 внутрішні капсули (За кадром 1 га → Базова Еліта 200 га → СН-1 у 50-км зоні → Подвійний вихід: Сидерат + Переробка);
- Матрицю вигоди кожного учасника (зокрема зростання доходу НУС НААН у 4,6 раза проти 46 тис. грн разового продажу);
- Правило подачі через комерційного Провайдера ІІБ замість бюджетної установи НААН.
"""

import io
from datetime import datetime
from docx import Document
from docx.shared import Pt
from grant_scraper import evaluate_grants
from agro_registry_service import resolve_grant_operator


def create_grant_document(profile_data: dict, grants_list: list = None) -> io.BytesIO:
    doc = Document()

    normal_style = doc.styles["Normal"]
    normal_style.font.name = "Arial"
    normal_style.font.size = Pt(10.5)

    operator_info = resolve_grant_operator(profile_data)

    doc.add_heading("ЕСКІЗНИЙ ПРОЄКТ (ДРАФТ) ТА РАМКОВА УГОДА ІННОВАЦІЙНОГО АГРОКЛАСТЕРУ", 0)
    doc.add_paragraph(
        f"Дата формування: {datetime.utcnow().strftime('%d.%m.%Y')} | "
        f"Архітектор та Провайдер системи (Надбудова): ТОВ «Інститут інноваційної біоекономіки» (ІІБ, ЄДРПОУ 40125890)\n"
        f"Наукове ядро (Оригінатор ОІВ): ННЦ «Інститут землеробства НААН» (ЄДРПОУ 00496802)\n"
        f"Об'єкт трансферу: Сорт гірчиці білої «Біла Принцеса» (Патент №180923, Свідоцтво №180501)"
    )

    doc.add_heading("1. Паспорт верифікованого учасника та Оператор залучення фінансування", level=1)

    fields = [
        ("Верифікований суб'єкт кластеру (ЄДРПОУ)", f"{profile_data.get('company_name', 'Не вказано')} ({profile_data.get('edrpou', '00496802')})"),
        ("Галузевий профіль (Агро-КВЕД)", profile_data.get("kved", "01.11 / 72.19 Аграрне виробництво та наука")),
        ("Роль у кластерній матриці ІІБ", profile_data.get("activity_type", "Учасник кластерного циклу")),
        ("Офіційний Заявник (Оператор гранту/інвестицій)", f"{operator_info['operator_name']} (ЄДРПОУ {operator_info['operator_edrpou']})"),
        ("Статус наукового партнера (НУС НААН)", operator_info["science_partner_role"]),
        ("Масштаб посівів та обсяг виробництва", profile_data.get("size_category", "1 000 га товарного циклу у 50-км зоні")),
        ("Розрахункова маржа, роялті НААН та точка входу", profile_data.get("employees_count", "Визначено за матрицею Драфту ІІБ"))
    ]

    table = doc.add_table(rows=1, cols=2)
    table.style = "Table Grid"
    hdr = table.rows[0].cells
    hdr[0].text = "Параметр кластерного паспорта"
    hdr[1].text = "Верифіковане значення"

    for label, value in fields:
        row_cells = table.add_row().cells
        row_cells[0].text = label
        row_cells[1].text = str(value)

    p_rule = doc.add_paragraph()
    p_rule.add_run("Примітка щодо оператора подачі (Правило ІІБ): ").bold = True
    p_rule.add_run(operator_info["explanation"])

    doc.add_heading("2. Архітектура Драфту ІІБ: Надбудова Провайдера та 4 внутрішні капсули", level=1)
    doc.add_paragraph(
        "Драфт (Ескізний проєкт) — це економіко-договірна надбудова ТОВ «ІІБ» НАД усім виробничим ланцюгом, "
        "яка перекладає селекційну новацію з мови біології на мову маржі, вигоди та контрактів кожного учасника:"
    )

    tech_stages = [
        (
            "За кадром • Наукова Новація (1 га)",
            "Оригінальне насіння / Супереліта (вал 1,5 т → 1,0 т у стартап)",
            "ННЦ «ІЗ НААН»: селекційна ділянка 1 га, підтримка чистоти сорту «Біла Принцеса». Опція 1,0 т супереліти передається під розмноження."
        ),
        (
            "Капсула І • Базове насінництво (200 га)",
            "Елітне насіння (120 т кондиційної Еліти + 180 т технічної фракції)",
            "Дослідне / базове насінницьке господарство за форвардним контрактом ІІБ розмножує 1 т супереліти на 200 га (просторова ізоляція 1000 м)."
        ),
        (
            "Капсула ІІ • Масштабування СН-1/СН-2 (300–5000+ га)",
            "Сертифіковане насіння І/ІІ репродукції та товарне зерно",
            "Фермерський пул у радіусі 50 км від переробника. Сплата погектарного роялті НААН: 800 грн/га (базові), 200 грн/га (насіннєві), 100 грн/га (товарні)."
        ),
        (
            "Капсула ІІІ • Подвійне замикання ринку",
            "Вихід А: Сидерат (мішки 25 кг) | Вихід Б: Олія (30%), Порошок (50%), Шрот (15%)",
            "Агрономічний вихід (сидерація, азот, біофумігація проти нематод) + Промислова переробка на заводі у 50-км зоні та експорт у ЄС (Німеччина, Нідерланди)."
        )
    ]

    tech_table = doc.add_table(rows=1, cols=3)
    tech_table.style = "Table Grid"
    th = tech_table.rows[0].cells
    th[0].text = "Капсула технологічного ланцюга"
    th[1].text = "Продукт генерації"
    th[2].text = "Договірний та економічний механізм (Драфт ІІБ)"

    for st, prod, desc in tech_stages:
        rc = tech_table.add_row().cells
        rc[0].text = st
        rc[1].text = prod
        rc[2].text = desc

    p_proc = doc.add_paragraph()
    p_proc.add_run("Технологічний баланс глибокої переробки Zero-Waste (Вихід Б): ").bold = True
    p_proc.add_run(
        "З 1 т насіння сорту «Біла Принцеса» виробляється: 300 кг гірчичної олії холодного віджиму (базова ціна 90 000 грн/т), "
        "500 кг харчового/промислового гірчичного порошку (25 000 грн/т), "
        "150 кг кормового білкового шроту (10 000 грн/т) та 50 кг насіннєвої фракції (40 000 грн/т). "
        "Загальна виручка глибокої переробки досягає 43 000–51 600 грн/т, що генерує +135% чистої доданої вартості проти продажу сировини."
    )

    doc.add_heading("3. Мова вигоди: економічний інтерес кожного учасника кластеру", level=1)
    benefits = [
        (
            "Наукова установа (ННЦ «ІЗ НААН»): ",
            "Самостійний продаж насіння з 1 га без стартапу приносить лише 46 тис. грн чистого надходження. "
            "Інтеграція у кластер через Провайдера ІІБ забезпечує компенсацію супереліти, контракт на 120 т еліти "
            "та погектарне роялті (до 2,36 млн грн на 20 000 га), що збільшує дохід інституту в 4,6 раза."
        ),
        (
            "Фермерські та насінницькі господарства (радіус 50 км): ",
            "Отримують високопродуктивний посухостійкий сорт (до 2,2–3,0 т/га), гарантований контракт викупу (Off-take) "
            "заводом-переробником та власний сидерат для відновлення азоту і боротьби з нематодами."
        ),
        (
            "Переробний завод (Олія, порошок, шрот): ",
            "Отримує стабільну сировинну базу в радіусі 50 км із однорідними показниками олійності та ефірних олій "
            "під довгострокові експортні контракти з покупцями у Німеччині та Нідерландах."
        )
    ]
    for title_b, text_b in benefits:
        pb = doc.add_paragraph()
        pb.add_run(f"• {title_b}").bold = True
        pb.add_run(text_b)

    doc.add_heading("4. Вирізка Стартап-лотів під джерела фінансування (Скоринг ІІБ)", level=1)

    scored_models = evaluate_grants(profile_data, grants_list)
    for item in scored_models[:4]:
        p = doc.add_paragraph()
        p.add_run(f"• {item['title']} (Індекс відповідності: {item['score']}%)\n").bold = True
        p.add_run(f"Джерело / Фінансовий інститут: {item['donor']}\n")
        p.add_run(f"Оператор подачі (Заявник): {item['operator_name']} (ЄДРПОУ {item['operator_edrpou']})\n")
        p.add_run(f"Обсяг фінансування лоту: {item['max_amount']} (Власний внесок: від {item['min_own_percent']}%)\n")
        p.add_run(f"Обґрунтування вирізки з Драфту: {item['requirements']}")

    footer_p = doc.add_paragraph(
        "\nДокумент сформовано інформаційно-аналітичною платформою AgroCluster Analytics "
        "(ТОВ «Інститут інноваційної біоекономіки» & НААН України). Готово до контрактації учасників кластеру."
    )
    footer_p.runs[0].italic = True

    file_stream = io.BytesIO()
    doc.save(file_stream)
    file_stream.seek(0)
    return file_stream
